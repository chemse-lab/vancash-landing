def stamp(t):
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def main():
    tl = json.loads((FILM / "vo_timeline.json").read_text())
    shift = {s["id"]: s["shift"] for s in tl["sections"]}
    out, prev_end = [], 0.0
    for i, (sid, a, b, line) in enumerate(CUES, 1):
        t0 = max(prev_end, shift[sid] + a - 0.05)       # a hair early reads better than late
        t1 = shift[sid] + b + 0.25
        if i < len(CUES):                               # never overlap the next cue
            nsid, na, _, _ = CUES[i]
            t1 = min(t1, shift[nsid] + na - 0.06)
        out.append(f"{i}\n{stamp(t0)} --> {stamp(t1)}\n{line}\n")
        prev_end = t1
    (HERE / "ep01.ar.srt").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(CUES)} cues -> {HERE / 'ep01.ar.srt'}")


if __name__ == "__main__":
    main()
